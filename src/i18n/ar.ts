type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly { question: string; answer: string }[]
    ? { question: string; answer: string }[]
    : T[K] extends object
    ? DeepStringify<T[K]>
    : T[K];
};

